-- =============================================================================
-- Migración: pedidos y pedido_items (compra/venta en LiveMarket)
-- =============================================================================
-- Objetivo: crear el soporte de datos que ya usan las rutas
--   * GET/POST   /api/pedidos
--   * GET/PATCH/DELETE /api/pedidos/[id]
--
-- Modelo de negocio (CONFIRMADO):
--   * El comprador confirma el pedido desde la página de Tienda (/comprar).
--   * El pedido se envía SIEMPRE a la empresa (vendedor) dueña del producto:
--     si el carrito tiene productos de varias empresas, el backend crea UN
--     pedido por vendedor.
--   * Antes de confirmar, el comprador define ciudad, municipio, dirección,
--     referencia y método de pago (datos de entrega).
--   * El vendedor gestiona el estado; el comprador puede corregir la entrega
--     mientras el pedido siga 'pendiente'.
--
-- Estados válidos: 'pendiente' | 'confirmado' | 'enviado' | 'entregado' | 'cancelado'.
--
-- IMPORTANTE (tipos): se asume que public.usuarios.id es uuid y que
--   public.productos.id es entero (bigint). Si en tu proyecto esos tipos
--   difieren, ajusta las columnas comprador_id/vendedor_id/producto_id antes
--   de ejecutar. Las tablas se crean con `if not exists`: si ya existen, esta
--   migración sólo aplica los GRANT/RLS/índices que falten.
--
-- Seguridad: el backend consulta con el token del usuario, por lo que RLS
--   SÍ se aplica. Las políticas de abajo permiten únicamente a las dos partes
--   del pedido (comprador y vendedor) leer/editar sus propios pedidos, y sólo
--   al comprador crear pedidos.
--
-- Aplicación (manual, NO automática):
--   A) Panel de Supabase -> SQL Editor -> pegar y ejecutar.
--   B) Supabase CLI:  supabase db push  (proyecto enlazado).
-- =============================================================================

-- 0) Función de apoyo para mantener updated_at (idempotente).
create or replace function public.tocar_updated_at_pedidos()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- 1) Tabla de pedidos ---------------------------------------------------------
create table if not exists public.pedidos (
  id                  bigint generated by default as identity primary key,
  comprador_id        uuid   not null references public.usuarios(id) on delete cascade,
  vendedor_id         uuid   not null references public.usuarios(id) on delete cascade,
  total               numeric(12,2) not null default 0,
  estado              text   not null default 'pendiente'
                              check (estado in ('pendiente','confirmado','enviado','entregado','cancelado')),
  metodo_pago         text   not null,
  ciudad              text   not null,
  municipio           text   not null,
  direccion           text   not null,
  referencia_entrega  text,
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now()
);

create index if not exists pedidos_comprador_idx on public.pedidos (comprador_id);
create index if not exists pedidos_vendedor_idx  on public.pedidos (vendedor_id);
create index if not exists pedidos_estado_idx    on public.pedidos (estado);

-- Trigger de updated_at (se recrea para dejar el nombre estable).
drop trigger if exists trg_pedidos_updated_at on public.pedidos;
create trigger trg_pedidos_updated_at
  before update on public.pedidos
  for each row
  execute function public.tocar_updated_at_pedidos();

-- 2) Tabla de items del pedido -----------------------------------------------
create table if not exists public.pedido_items (
  id               bigint generated by default as identity primary key,
  pedido_id        bigint not null references public.pedidos(id) on delete cascade,
  producto_id      bigint not null references public.productos(id) on delete restrict,
  cantidad         integer not null check (cantidad > 0),
  precio_unitario  numeric(12,2) not null check (precio_unitario >= 0),
  created_at       timestamptz not null default now()
);

create index if not exists pedido_items_pedido_idx   on public.pedido_items (pedido_id);
create index if not exists pedido_items_producto_idx on public.pedido_items (producto_id);

-- 3) Privilegios (el backend usa el token del usuario -> rol authenticated) ---
grant select, insert, update, delete on public.pedidos      to authenticated;
grant select, insert, update, delete on public.pedido_items to authenticated;
-- Las sequences generadas por identity también necesitan USAGE para INSERT.
grant usage on all sequences in schema public to authenticated;

-- 4) RLS ---------------------------------------------------------------------
alter table public.pedidos      enable row level security;
alter table public.pedido_items enable row level security;

-- 4a) pedidos: sólo comprador y vendedor ven su pedido.
do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'pedidos' and policyname = 'pedidos_leer_propios'
  ) then
    create policy "pedidos_leer_propios" on public.pedidos
      for select to authenticated
      using (comprador_id = auth.uid() or vendedor_id = auth.uid());
  end if;

  -- 4b) pedidos: sólo el comprador crea, y siempre a su nombre.
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'pedidos' and policyname = 'pedidos_crear_comprador'
  ) then
    create policy "pedidos_crear_comprador" on public.pedidos
      for insert to authenticated
      with check (comprador_id = auth.uid());
  end if;

  -- 4c) pedidos: comprador o vendedor pueden actualizar su pedido
  --     (el vendedor cambia estado; el comprador corrige entrega si pendiente;
  --      el backend valida la regla fina).
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'pedidos' and policyname = 'pedidos_actualizar_partes'
  ) then
    create policy "pedidos_actualizar_partes" on public.pedidos
      for update to authenticated
      using (comprador_id = auth.uid() or vendedor_id = auth.uid())
      with check (comprador_id = auth.uid() or vendedor_id = auth.uid());
  end if;

  -- 4d) pedidos: comprador o vendedor pueden eliminar su pedido
  --     (el backend restringe a estados no despachados).
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'pedidos' and policyname = 'pedidos_eliminar_partes'
  ) then
    create policy "pedidos_eliminar_partes" on public.pedidos
      for delete to authenticated
      using (comprador_id = auth.uid() or vendedor_id = auth.uid());
  end if;

  -- 4e) pedido_items: lectura si el pedido es visible para el usuario.
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'pedido_items' and policyname = 'pedido_items_leer_pedido_propio'
  ) then
    create policy "pedido_items_leer_pedido_propio" on public.pedido_items
      for select to authenticated
      using (
        exists (
          select 1 from public.pedidos p
          where p.id = pedido_items.pedido_id
            and (p.comprador_id = auth.uid() or p.vendedor_id = auth.uid())
        )
      );
  end if;

  -- 4f) pedido_items: el comprador agrega items de su propio pedido.
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'pedido_items' and policyname = 'pedido_items_insertar_comprador'
  ) then
    create policy "pedido_items_insertar_comprador" on public.pedido_items
      for insert to authenticated
      with check (
        exists (
          select 1 from public.pedidos p
          where p.id = pedido_items.pedido_id
            and p.comprador_id = auth.uid()
        )
      );
  end if;

  -- 4g) pedido_items: se pueden actualizar/eliminar si el pedido es del usuario.
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'pedido_items' and policyname = 'pedido_items_modificar_propio'
  ) then
    create policy "pedido_items_modificar_propio" on public.pedido_items
      for all to authenticated
      using (
        exists (
          select 1 from public.pedidos p
          where p.id = pedido_items.pedido_id
            and (p.comprador_id = auth.uid() or p.vendedor_id = auth.uid())
        )
      )
      with check (
        exists (
          select 1 from public.pedidos p
          where p.id = pedido_items.pedido_id
            and (p.comprador_id = auth.uid() or p.vendedor_id = auth.uid())
        )
      );
  end if;
end
$$;
